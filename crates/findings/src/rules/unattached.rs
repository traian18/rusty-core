use super::{FindingRule, FindingsInput};
use crate::model::{Confidence, Draft, Evidence, FindingKind, Severity};

/// Rust files no Cargo target root reaches through `mod` declarations.
pub struct UnattachedFileRule;

impl FindingRule for UnattachedFileRule {
    fn id(&self) -> &'static str {
        "unattached-file"
    }
    fn version(&self) -> u32 {
        1
    }
    fn kind(&self) -> FindingKind {
        FindingKind::Measurable
    }
    fn description(&self) -> &'static str {
        "Rust source files that no `mod` declaration chain from a Cargo target reaches."
    }
    fn evaluate(&self, input: &FindingsInput<'_>) -> Vec<Draft> {
        input
            .repository
            .imports
            .unattached
            .iter()
            .map(|file| {
                let package = input.view.package_of_file(file);
                Draft {
                    key: file.as_path().display().to_string(),
                    severity: Severity::Low,
                    // Modules generated by macros or cfg are not evaluated, so a miss is possible.
                    confidence: Confidence::Medium,
                    title: format!("{} is not part of any crate", file.as_path().display()),
                    summary: "No `mod` declaration reachable from a Cargo target root includes this file, so the compiler never sees it.".to_owned(),
                    rationale: "Either the file is leftover, or its `mod` line is missing or sits behind a path attribute the analysis does not follow; declare the module, delete the file, or suppress this with a reason if a macro includes it.".to_owned(),
                    subjects: vec![file.clone()],
                    packages: package.map(|p| p.id.clone()).into_iter().collect(),
                    impact: 1,
                    evidence: Evidence { files: vec![file.clone()], ..Evidence::default() },
                    spans: Vec::new(),
                }
            })
            .collect()
    }
}
