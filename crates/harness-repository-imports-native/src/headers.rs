/// Whether `header` is a standard C, POSIX or C++ header, or one under a system directory.
pub fn is_system_header(header: &str) -> bool {
    C.contains(&header)
        || POSIX.contains(&header)
        || CPP.contains(&header)
        || [
            "sys/", "linux/", "asm/", "bits/", "arpa/", "netinet/", "net/",
        ]
        .iter()
        .any(|prefix| header.starts_with(prefix))
}
