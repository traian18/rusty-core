pub fn is_stdlib(top_level: &str) -> bool {
    STDLIB.contains(&top_level)
}

/// PEP 503 normalisation: lower case, runs of `-`, `_`, `.` become one `-`.
pub fn normalize(distribution: &str) -> String {
    let mut out = String::new();
    let mut separator = false;
    for ch in distribution.trim().chars() {
        if matches!(ch, '-' | '_' | '.') {
            separator = true;
        } else {
            if separator && !out.is_empty() {
                out.push('-');
            }
            separator = false;
            out.push(ch.to_ascii_lowercase());
        }
    }
    out
}

/// The distribution names an import of `top_level` may come from: its own normalised name and any
/// known alias.
pub fn candidate_distributions(top_level: &str) -> Vec<String> {
    let mut names = vec![normalize(top_level)];
    names.extend(
        ALIASES
            .iter()
            .filter(|(import, _)| *import == top_level)
            .map(|(_, dist)| normalize(dist)),
    );
    names
}
